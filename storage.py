def load_recipients() -> list[dict]:
    if not os.path.exists(RECIPIENTS_FILE):
        save_recipients(DEFAULT_RECIPIENTS)
        return list(DEFAULT_RECIPIENTS)
    try:
        with open(RECIPIENTS_FILE, "r", encoding="utf-8") as f:
            saved = json.load(f)
    except Exception:
        save_recipients(DEFAULT_RECIPIENTS)
        return list(DEFAULT_RECIPIENTS)

    # Автоматически подливаем новых получателей из встроенной базы
    existing_names = {r.get("name", "").strip().lower() for r in saved}
    added = False
    for item in DEFAULT_RECIPIENTS:
        if item["name"].strip().lower() not in existing_names:
            saved.append(item)
            existing_names.add(item["name"].strip().lower())
            added = True
    if added:
        save_recipients(saved)
    return saved


def save_recipients(items: list[dict]) -> None:
    with open(RECIPIENTS_FILE, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=2)


def load_history() -> list[dict]:
    if not os.path.exists(HISTORY_FILE):
        return []
    try:
        with open(HISTORY_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return []


def add_history_entry(entry: dict) -> None:
    history = load_history()
    entry["created_at"] = datetime.datetime.now().strftime("%d.%m.%Y %H:%M")
    history.insert(0, entry)
    with open(HISTORY_FILE, "w", encoding="utf-8") as f:
        json.dump(history[:200], f, ensure_ascii=False, indent=2)
